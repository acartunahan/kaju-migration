  WHERE DECODE(d.DEPO_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_DEPO'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.DEPO'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ZIMMET_KAYDI.TARIH', COUNT(*) FROM ZIMMET_KAYDI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ZIMMET_KAYDI' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.TARIH,
          CASE WHEN JSON_VALUE(h.HAM_JSON, '$.TARIH') IN ('1899-12-30T00:00:00', '1900-01-01T00:00:00') THEN NULL
               ELSE TO_TIMESTAMP(JSON_VALUE(h.HAM_JSON, '$.TARIH'), 'YYYY-MM-DD"T"HH24:MI:SS') END, 0, 1) = 1
UNION ALL SELECT 'ZIMMET_KAYDI.ISLEM_YAPAN_SICIL', COUNT(*) FROM ZIMMET_KAYDI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ZIMMET_KAYDI' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ISLEM_YAPAN_SICIL, TRIM(JSON_VALUE(h.HAM_JSON, '$.KULLANICI')), 0, 1) = 1

) ORDER BY HATALI DESC, KONTROL;
