-- =====================================================================================
-- ALAN MUTABAKATI (hedef şemada, SALT OKUNUR)
--
-- GERCEK çalışmadan sonra HEDEF kullanıcısıyla çalıştırılır. Tek bir sorgudur.
-- Her satır bir kontroldür; HATALI = 0 olmalı.
--
-- Yöntem: MIG_HAM_VERI, legacy satırın göç anındaki tam kopyasıdır (JSON). Hedefteki her alan,
-- bu JSON'daki legacy değerine migration'ın kuralları SQL ile tekrar uygulanarak karşılaştırılır:
--   * metin: birebir            * kod: RTRIM              * sicil: TRIM
--   * tarih: Delphi boş tarihi (1899-12-30 / 1900-01-01) → NULL (zorunlu alanlarda korunur)
--   * referans: MIG_KIMLIK_ESLEME'de tek eşleşme → o ID; yok ya da birden fazla → NULL
--   * enum: application.yml'deki VARSAYILAN eşlemeler. yml'ye yeni eşleme eklendiyse ilgili
--     satır HATALI gösterir; o durumda DECODE listesine aynı eşlemeyi ekleyin.
-- Bilinen fark: Java strip() tüm Unicode boşlukları, Oracle TRIM sadece boşluk karakterini siler.
-- Sekme gibi karakterler içeren siciller HATALI görünebilir; bunlar ayrıca incelenir.
--
-- Gereksinim: Oracle 12.2+ (JSON_VALUE, TO_NUMBER ... DEFAULT NULL ON CONVERSION ERROR).
-- Sadece GERCEK mod verisini (KURU = 0) kontrol eder.
-- =====================================================================================
SELECT KONTROL, HATALI FROM (

-- ---------------------------------------------------------------- 0. bütünlük
-- Arşivlenen tablolar (kapsam kararı): eşleme ve ham veri HEDEF_TABLO = 'ARSIV', HEDEF_ID = NULL.
-- Bunlar ne aktarılmış ne reddedilmiş sayılır; ayrı kontrol edilir.
SELECT '00 ESLEME: ham verisi olmayan' AS KONTROL, COUNT(*) AS HATALI
FROM MIG_KIMLIK_ESLEME e
WHERE e.KURU = 0
  AND NOT EXISTS (SELECT 1 FROM MIG_HAM_VERI h WHERE h.KAYNAK_TABLO = e.KAYNAK_TABLO
                  AND h.KAYNAK_ROWID = e.KAYNAK_ROWID
                  AND (h.HEDEF_ID = e.HEDEF_ID OR (e.HEDEF_TABLO = 'ARSIV' AND h.HEDEF_TABLO = 'ARSIV')))
UNION ALL
SELECT '00 HAM_VERI: aktarılmamış ama RED kaydı yok', COUNT(*)
FROM MIG_HAM_VERI h
WHERE h.HEDEF_ID IS NULL AND NVL(h.HEDEF_TABLO, '-') <> 'ARSIV'
  AND NOT EXISTS (SELECT 1 FROM MIG_SORUN s WHERE s.KURU = 0 AND s.SEVIYE = 'RED'
                  AND s.KAYNAK_TABLO = h.KAYNAK_TABLO AND s.KAYNAK_ROWID = h.KAYNAK_ROWID)
UNION ALL
SELECT '00 HAM_VERI: aktarılmamış ama eşlemesi var', COUNT(*)
FROM MIG_HAM_VERI h
WHERE h.HEDEF_ID IS NULL AND NVL(h.HEDEF_TABLO, '-') <> 'ARSIV'
  AND EXISTS (SELECT 1 FROM MIG_KIMLIK_ESLEME e WHERE e.KURU = 0
              AND e.KAYNAK_TABLO = h.KAYNAK_TABLO AND e.KAYNAK_ROWID = h.KAYNAK_ROWID)
UNION ALL
SELECT '00 ARSIV: eşlemesi olmayan arşiv satırı', COUNT(*)
FROM MIG_HAM_VERI h
WHERE h.HEDEF_TABLO = 'ARSIV'
  AND NOT EXISTS (SELECT 1 FROM MIG_KIMLIK_ESLEME e WHERE e.KURU = 0 AND e.HEDEF_TABLO = 'ARSIV'
                  AND e.KAYNAK_TABLO = h.KAYNAK_TABLO AND e.KAYNAK_ROWID = h.KAYNAK_ROWID)

-- ---------------------------------------------------------------- DEPO (RESAT_DEPO)
UNION ALL SELECT 'DEPO: ham verisi olmayan göç satırı', COUNT(*) FROM DEPO d
  WHERE d.OLUSTURAN = 'MIGRATION' AND NOT EXISTS (SELECT 1 FROM MIG_HAM_VERI h WHERE h.HEDEF_TABLO = 'DEPO' AND h.HEDEF_ID = d.ID)
UNION ALL SELECT 'DEPO.AD', COUNT(*) FROM DEPO d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'DEPO' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.AD, JSON_VALUE(h.HAM_JSON, '$.ADI'), 0, 1) = 1
UNION ALL SELECT 'DEPO.ACIKLAMA', COUNT(*) FROM DEPO d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'DEPO' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ACIKLAMA, JSON_VALUE(h.HAM_JSON, '$.ACIKLAMA'), 0, 1) = 1
UNION ALL SELECT 'DEPO.DURUM_KODU', COUNT(*) FROM DEPO d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'DEPO' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.DURUM_KODU, RTRIM(JSON_VALUE(h.HAM_JSON, '$.DURUM')), 0, 1) = 1
UNION ALL SELECT 'DEPO.KAYIT_TARIHI', COUNT(*) FROM DEPO d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'DEPO' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.KAYIT_TARIHI,
          CASE WHEN JSON_VALUE(h.HAM_JSON, '$.K_TARIH') IN ('1899-12-30T00:00:00', '1900-01-01T00:00:00') THEN NULL
               ELSE TO_TIMESTAMP(JSON_VALUE(h.HAM_JSON, '$.K_TARIH'), 'YYYY-MM-DD"T"HH24:MI:SS') END, 0, 1) = 1
UNION ALL SELECT 'DEPO.SORUMLU_SICIL', COUNT(*) FROM DEPO d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'DEPO' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.SORUMLU_SICIL, TRIM(JSON_VALUE(h.HAM_JSON, '$.PERSONELKODU')), 0, 1) = 1

-- ---------------------------------------------------------------- ENVANTER, TUR = DEMIRBAS (R_DEMIRBAS)
UNION ALL SELECT 'ENVANTER(DEMIRBAS): ham verisi olmayan göç satırı', COUNT(*) FROM ENVANTER d
  WHERE d.TUR = 'DEMIRBAS' AND d.OLUSTURAN = 'MIGRATION' AND NOT EXISTS (SELECT 1 FROM MIG_HAM_VERI h WHERE h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID)
UNION ALL SELECT 'ENVANTER(DEMIRBAS).DEMIRBAS_NO', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.DEMIRBAS_NO, JSON_VALUE(h.HAM_JSON, '$.D_NO' RETURNING NUMBER), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).SERI_NO', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.SERI_NO, JSON_VALUE(h.HAM_JSON, '$.SERI_NO'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).BIRIM_KODU', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.BIRIM_KODU, JSON_VALUE(h.HAM_JSON, '$.BIRIM' RETURNING NUMBER), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).KATEGORI_ID', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.KATEGORI_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_SABIT_KOD'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.SABITKOD'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).DEPO_ID', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.DEPO_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_DEPO'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.DEPO_GUID'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).ALIM_YOLU', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ALIM_YOLU, DECODE(JSON_VALUE(h.HAM_JSON, '$.ALIM_YOLU'),
          '0', 'BILGI_ISLEM_DB', '1', 'IKMAL_BAKIM_DB', '2', 'HABERLESME_DB', '3', 'HABERALMA_OD', '4', 'KAYNAGI_BELIRSIZ'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).AD', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.AD, JSON_VALUE(h.HAM_JSON, '$.M_ADI'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).MARKA_ID', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.MARKA_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_MARKA'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.MARKA'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).MODEL_ID', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.MODEL_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_MODEL'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.MODEL'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).IHALE_ID', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.IHALE_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_IHALE'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.IHALE_ID'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).GARANTI_BASLANGIC', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.GARANTI_BASLANGIC,
          CASE WHEN JSON_VALUE(h.HAM_JSON, '$.G_BAS_TAR') IN ('1899-12-30T00:00:00', '1900-01-01T00:00:00') THEN NULL
               ELSE TO_TIMESTAMP(JSON_VALUE(h.HAM_JSON, '$.G_BAS_TAR'), 'YYYY-MM-DD"T"HH24:MI:SS') END, 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).GARANTI_BITIS', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.GARANTI_BITIS,
          CASE WHEN JSON_VALUE(h.HAM_JSON, '$.G_BIT_TAR') IN ('1899-12-30T00:00:00', '1900-01-01T00:00:00') THEN NULL
               ELSE TO_TIMESTAMP(JSON_VALUE(h.HAM_JSON, '$.G_BIT_TAR'), 'YYYY-MM-DD"T"HH24:MI:SS') END, 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).ACIKLAMA', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ACIKLAMA, JSON_VALUE(h.HAM_JSON, '$.ACIKLAMA'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).DURUM', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.DURUM, DECODE(RTRIM(JSON_VALUE(h.HAM_JSON, '$.DURUM')), '1', 'NORMAL', '2', 'ARIZALI', '3', 'IADE'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).KAYIT_TARIHI (zorunlu, boş tarih korunur)', COUNT(*) FROM ENVANTER d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.KAYIT_TARIHI, TO_TIMESTAMP(JSON_VALUE(h.HAM_JSON, '$.K_TARIH'), 'YYYY-MM-DD"T"HH24:MI:SS'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).SAYMANLIK_NO', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.SAYMANLIK_NO, JSON_VALUE(h.HAM_JSON, '$.SAYMANLIKNO'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).ZIMMETLI_SICIL', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ZIMMETLI_SICIL, TRIM(JSON_VALUE(h.HAM_JSON, '$.PERSZIMMET')), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).IL_SUBE_DAIRE_BSK_NO', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.IL_SUBE_DAIRE_BSK_NO, JSON_VALUE(h.HAM_JSON, '$.ILSUBEDBASNO'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(DEMIRBAS).ALIM_TURU_KODU', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_DEMIRBAS' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ALIM_TURU_KODU, RTRIM(JSON_VALUE(h.HAM_JSON, '$.ALIM_TUR')), 0, 1) = 1

-- ---------------------------------------------------------------- ENVANTER, TUR = SARF (R_TUKETIMCINSLERI)
UNION ALL SELECT 'ENVANTER(SARF): ham verisi olmayan göç satırı', COUNT(*) FROM ENVANTER d
  WHERE d.TUR = 'SARF' AND d.OLUSTURAN = 'MIGRATION' AND NOT EXISTS (SELECT 1 FROM MIG_HAM_VERI h WHERE h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_TUKETIMCINSLERI' AND h.HEDEF_ID = d.ID)
UNION ALL SELECT 'ENVANTER(SARF).TUR', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_TUKETIMCINSLERI' AND h.HEDEF_ID = d.ID
  WHERE d.TUR <> 'SARF'
UNION ALL SELECT 'ENVANTER(SARF).AD', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_TUKETIMCINSLERI' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.AD, JSON_VALUE(h.HAM_JSON, '$.ADI'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(SARF).ACIKLAMA', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_TUKETIMCINSLERI' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ACIKLAMA, JSON_VALUE(h.HAM_JSON, '$.ACIKLAMA'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(SARF).DURUM_KODU', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_TUKETIMCINSLERI' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.DURUM_KODU, RTRIM(JSON_VALUE(h.HAM_JSON, '$.DURUM')), 0, 1) = 1
UNION ALL SELECT 'ENVANTER(SARF).KAYIT_TARIHI', COUNT(*) FROM ENVANTER d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER' AND h.KAYNAK_TABLO = 'R_TUKETIMCINSLERI' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.KAYIT_TARIHI,
          CASE WHEN JSON_VALUE(h.HAM_JSON, '$.K_TARIH') IN ('1899-12-30T00:00:00', '1900-01-01T00:00:00') THEN NULL
               ELSE TO_TIMESTAMP(JSON_VALUE(h.HAM_JSON, '$.K_TARIH'), 'YYYY-MM-DD"T"HH24:MI:SS') END, 0, 1) = 1

-- ---------------------------------------------------------------- MODEL.KATEGORI_ID (türetilmiş)
-- Kural: modelin demirbaşlarında tek bir dolu kategori varsa model o kategoridedir; yoksa boştur.
-- (Migration'dan sonra kullanıcı elle kategori girdiyse bu kontrol o modelleri gösterir.)
UNION ALL SELECT 'MODEL.KATEGORI_ID (türetme kuralı)', COUNT(*) FROM MODEL m
  WHERE m.TUR = 'DEMIRBAS'
    AND DECODE(m.KATEGORI_ID,
               (SELECT CASE WHEN COUNT(DISTINCT d.KATEGORI_ID) = 1 THEN MAX(d.KATEGORI_ID) END
                  FROM ENVANTER d WHERE d.MODEL_ID = m.ID), 0, 1) = 1

-- ---------------------------------------------------------------- BARKOD (R_BARKOD)
UNION ALL SELECT 'BARKOD: ham verisi olmayan göç satırı', COUNT(*) FROM BARKOD d
  WHERE d.OLUSTURAN = 'MIGRATION' AND NOT EXISTS (SELECT 1 FROM MIG_HAM_VERI h WHERE h.HEDEF_TABLO = 'BARKOD' AND h.HEDEF_ID = d.ID)
UNION ALL SELECT 'BARKOD.BARKOD', COUNT(*) FROM BARKOD d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'BARKOD' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.BARKOD, JSON_VALUE(h.HAM_JSON, '$.BARKOD'), 0, 1) = 1
UNION ALL SELECT 'BARKOD.SERI_NO_MU', COUNT(*) FROM BARKOD d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'BARKOD' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.SERI_NO_MU, DECODE(RTRIM(JSON_VALUE(h.HAM_JSON, '$.SERIMI')), 'H', 0, 'E', 1), 0, 1) = 1
UNION ALL SELECT 'BARKOD.ENVANTER_ID', COUNT(*) FROM BARKOD d JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'BARKOD' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ENVANTER_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'R_DEMIRBAS'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.MGUID'), '{'), '}')))), 0, 1) = 1

-- ---------------------------------------------------------------- ENVANTER_HAREKETI, TUR = DEMIRBAS (R_HAREKET)
UNION ALL SELECT 'ENVANTER_HAREKETI(DEMIRBAS): ham verisi olmayan göç satırı', COUNT(*) FROM ENVANTER_HAREKETI d
  WHERE d.TUR = 'DEMIRBAS' AND d.OLUSTURAN = 'MIGRATION' AND NOT EXISTS (SELECT 1 FROM MIG_HAM_VERI h WHERE h.HEDEF_TABLO = 'ENVANTER_HAREKETI' AND h.KAYNAK_TABLO = 'R_HAREKET' AND h.HEDEF_ID = d.ID)
UNION ALL SELECT 'ENVANTER_HAREKETI(DEMIRBAS).ENVANTER_ID', COUNT(*) FROM ENVANTER_HAREKETI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER_HAREKETI' AND h.KAYNAK_TABLO = 'R_HAREKET' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.ENVANTER_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'R_DEMIRBAS'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.MGUID'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER_HAREKETI(DEMIRBAS).HAREKET_ADI', COUNT(*) FROM ENVANTER_HAREKETI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER_HAREKETI' AND h.KAYNAK_TABLO = 'R_HAREKET' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.HAREKET_ADI, JSON_VALUE(h.HAM_JSON, '$.ADI'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER_HAREKETI(DEMIRBAS).NEREDEN_METNI', COUNT(*) FROM ENVANTER_HAREKETI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER_HAREKETI' AND h.KAYNAK_TABLO = 'R_HAREKET' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.NEREDEN_METNI, JSON_VALUE(h.HAM_JSON, '$.NERDEN'), 0, 1) = 1
UNION ALL SELECT 'ENVANTER_HAREKETI(DEMIRBAS).NEREDEN_DEPO_ID', COUNT(*) FROM ENVANTER_HAREKETI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER_HAREKETI' AND h.KAYNAK_TABLO = 'R_HAREKET' AND h.HEDEF_ID = d.ID
  WHERE DECODE(d.NEREDEN_DEPO_ID, (SELECT CASE WHEN COUNT(*) = 1 THEN MAX(e.HEDEF_ID) END FROM MIG_KIMLIK_ESLEME e
          WHERE e.KURU = 0 AND e.KAYNAK_TABLO = 'RESAT_DEPO'
            AND e.ESKI_ANAHTAR_NORM = UPPER(TRIM(REPLACE(REPLACE(JSON_VALUE(h.HAM_JSON, '$.NERDEN'), '{'), '}')))), 0, 1) = 1
UNION ALL SELECT 'ENVANTER_HAREKETI(DEMIRBAS).NEREYE_METNI', COUNT(*) FROM ENVANTER_HAREKETI d
  JOIN MIG_HAM_VERI h ON h.HEDEF_TABLO = 'ENVANTER_HAREKETI' AND h.KAYNAK_TABLO = 'R_HAREKET' AND h.HEDEF_ID = d.ID
