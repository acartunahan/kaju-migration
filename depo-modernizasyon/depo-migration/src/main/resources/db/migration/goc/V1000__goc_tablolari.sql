-- Her job instance için bir satır. Restart aynı satırı günceller.
CREATE TABLE MIG_CALISMA (
    ID              NUMBER(19)                  NOT NULL,
    CALISMA_MODU    VARCHAR2(10 CHAR)           NOT NULL,
    ETIKET          VARCHAR2(100 CHAR)          NOT NULL,
    ILK_BASLANGIC   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    SON_BASLANGIC   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    BITIS           TIMESTAMP(6) WITH TIME ZONE,
    DURUM           VARCHAR2(20 CHAR)           NOT NULL,
    DENEME_SAYISI   NUMBER(5)                   NOT NULL,
    RAPOR           CLOB,
    CONSTRAINT PK_MIG_CALISMA PRIMARY KEY (ID),
    CONSTRAINT CK_MIG_CALISMA_MOD CHECK (CALISMA_MODU IN ('KURU', 'GERCEK'))
);

-- Eski kimlik → yeni ID. Kaynak satır kimliği ROWID (K4).
-- KURU=1 satırları sadece kuru çalışmada üretilir (HEDEF_ID boş) ve bir sonraki kuru çalışmada silinir.
CREATE TABLE MIG_KIMLIK_ESLEME (
    ID                 NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CALISMA_ID         NUMBER(19)                  NOT NULL,
    KURU               NUMBER(1)                   NOT NULL,
    KAYNAK_TABLO       VARCHAR2(128 CHAR)          NOT NULL,
    KAYNAK_ROWID       VARCHAR2(32 CHAR)           NOT NULL,
    ESKI_ID            NUMBER,
    ESKI_ANAHTAR_HAM   VARCHAR2(100 CHAR),
    ESKI_ANAHTAR_NORM  VARCHAR2(100 CHAR),
    HEDEF_TABLO        VARCHAR2(128 CHAR)          NOT NULL,
    HEDEF_ID           NUMBER(19),
    OLUSTURMA_ZAMANI   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_MIG_KIMLIK_ESLEME PRIMARY KEY (ID),
    CONSTRAINT UK_MIG_KIMLIK_ESLEME_KAYNAK UNIQUE (KAYNAK_TABLO, KAYNAK_ROWID, KURU),
    CONSTRAINT CK_MIG_KIMLIK_ESLEME_KURU CHECK (KURU IN (0, 1)),
    -- GERCEK modda her eşlemenin hedef satırı olmalı; tek istisna arşivlenen tablolar
    -- (HEDEF_TABLO = 'ARSIV'): hedef tablosu yok, HEDEF_ID her zaman boş.
    CONSTRAINT CK_MIG_KIMLIK_ESLEME_HEDEF CHECK (KURU = 1 OR HEDEF_ID IS NOT NULL OR HEDEF_TABLO = 'ARSIV'),
    CONSTRAINT CK_MIG_KIMLIK_ESLEME_ARSIV CHECK (HEDEF_TABLO <> 'ARSIV' OR HEDEF_ID IS NULL)
);
-- Referans çözümlemesi (çocuk tablolar bu index ile ebeveyn arar).
CREATE INDEX IX_MIG_KIMLIK_ESLEME_ANAHTAR ON MIG_KIMLIK_ESLEME (KAYNAK_TABLO, ESKI_ANAHTAR_NORM, KURU);
CREATE INDEX IX_MIG_KIMLIK_ESLEME_HEDEF ON MIG_KIMLIK_ESLEME (HEDEF_TABLO, HEDEF_ID);

-- Reddedilen satırlar (RED) ve uyarılar (UYARI). RED satırlarında ham satır JSON'u da tutulur.
CREATE TABLE MIG_SORUN (
    ID             NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    CALISMA_ID     NUMBER(19)                  NOT NULL,
    KURU           NUMBER(1)                   NOT NULL,
    SEVIYE         VARCHAR2(10 CHAR)           NOT NULL,
    KOD            VARCHAR2(40 CHAR)           NOT NULL,
    KAYNAK_TABLO   VARCHAR2(128 CHAR),
    KAYNAK_ROWID   VARCHAR2(32 CHAR),
    ESKI_ANAHTAR   VARCHAR2(100 CHAR),
    KOLON          VARCHAR2(128 CHAR),
    HAM_DEGER      VARCHAR2(1000 CHAR),
    MESAJ          VARCHAR2(1000 CHAR),
    HAM_JSON       CLOB,
    ZAMAN          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_MIG_SORUN PRIMARY KEY (ID),
    CONSTRAINT CK_MIG_SORUN_SEVIYE CHECK (SEVIYE IN ('RED', 'UYARI')),
    CONSTRAINT CK_MIG_SORUN_KURU CHECK (KURU IN (0, 1))
);
CREATE INDEX IX_MIG_SORUN_CALISMA ON MIG_SORUN (CALISMA_ID, KURU, KAYNAK_TABLO, SEVIYE, KOD);
CREATE INDEX IX_MIG_SORUN_KAYNAK ON MIG_SORUN (KAYNAK_TABLO, KAYNAK_ROWID);

-- Her legacy satırın tamamı (K1). Sadece GERCEK modda yazılır.
-- HEDEF_ID boşsa satır hedefe aktarılmadı (bkz. MIG_SORUN).
CREATE TABLE MIG_HAM_VERI (
    KAYNAK_TABLO   VARCHAR2(128 CHAR)          NOT NULL,
    KAYNAK_ROWID   VARCHAR2(32 CHAR)           NOT NULL,
    CALISMA_ID     NUMBER(19)                  NOT NULL,
    HEDEF_TABLO    VARCHAR2(128 CHAR),
    HEDEF_ID       NUMBER(19),
    HAM_JSON       CLOB                        NOT NULL,
    ZAMAN          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_MIG_HAM_VERI PRIMARY KEY (KAYNAK_TABLO, KAYNAK_ROWID)
);
CREATE INDEX IX_MIG_HAM_VERI_HEDEF ON MIG_HAM_VERI (HEDEF_TABLO, HEDEF_ID);
